/*
 * c_trace.mjs - replay every golden scenario on the DEBUG_TRACE ROM in Mesen and diff the C
 * engine's trace against tests/golden/*.txt (frame exact).
 *
 *   node tests/c_trace.mjs [rom] [noi] [scenario ...]
 * Normally run through tests/run_c_trace.ps1 (lock, build -Trace, start/stop Mesen).
 * Protocol: src/trace.h.  Scenarios = the plans/--init of tests/run_models.ps1; the start state
 * not given there is the Altirra checkpoint (START + 600 frames): $90/$8F from golden row 0
 * minus one, time $49, thief x $B1 path $0B anim 3, Kop at level start.
 * Columns compared = the ones the python model tests compare, plus $90/$8F (generated by the C
 * engine).  Other recorded columns are reported as "info" only.  Full C traces are written to
 * build/c_trace/<name>.txt in the golden format.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { init, callTool, readBytes, writeBytes, sleep, symbolsFromNoi, requireSymbol } from './mcp_client.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const rom = path.resolve(args[0] && args[0].endsWith('.nes') ? args.shift() : path.join(ROOT, 'roms', 'keystone_kapers_trace.nes'));
const noi = path.resolve(args[0] && args[0].endsWith('.noi') ? args.shift() : rom.replace(/\.nes$/, '.noi'));
const only = args;

/* record layout (src/trace.h) */
const REC = [0x90, 0x8F, 0x8E, 0x6B, 0x2C, 0x2D, 0x2E, 0x2F, 0x1D, 0x1E, 0x1C, 0x20, 0x0C, 0x19, 0x1B, 0x1F, 0x11, 0x28, 0x63, 0x1A];
const TRACE_ROWS = 32, TRACE_COLS = REC.length, PLAN_MAX = 16;

const OLD = [0x90, 0x2C, 0x1D, 0x1E, 0x19, 0x1C, 0x20, 0x0C];
const ESC = [0x90, 0x8F, 0x2C, 0x2D, 0x1D, 0x1E, 0x1C, 0x20, 0x0C, 0x19];
const SCENARIOS = [
    { name: 'kop_a', golden: 'kop_a.txt', check: OLD, mask: { 0x1C: 0x1F },
      plan: 'right:100,left:60,fire:2,centre:30,left+fire:45,right+fire:45,down:15,left+down:15,left:75,centre:20' },
    { name: 'kop_b', golden: 'kop_b.txt', check: OLD, mask: { 0x1C: 0x1F },
      plan: 'left:90,right:30,right:100,fire:3,left+fire:40,down:5,left:30' },
    { name: 'esc0', golden: 'kop_esc.txt', check: ESC, plan: 'left:200,right:60,left:40',
      init: { screen: 7, path: 0x07, x0: 0xB0 } },
    { name: 'esc1', golden: 'kop_esc1.txt', check: [...ESC, 0x2E], plan: 'right:200,left:20',
      init: { screen: 0, path: 0x0F, x1: 0x50, c1c: 0x20 } },
    { name: 'esc2', golden: 'kop_esc2.txt', check: [...ESC, 0x2E], plan: 'left:200,right:20',
      init: { screen: 7, path: 0x17, x2: 0xB0, c1c: 0x40 } },
    { name: 'elev_a', golden: 'elev_a.txt', check: [0x90, 0x8F, 0x8E, 0x6B, 0x2C, 0x1D, 0x1E, 0x1C, 0x20, 0x0C],
      plan: 'centre:10,up:5,centre:400,down:5,centre:30,right:30,centre:10',
      init: { screen: 4, path: 0x04, e8e: 0xE0, e6b: 0, x0: 0x78 } },
    { name: 'elev_b', golden: 'elev_b.txt', check: [0x90, 0x8F, 0x8E, 0x6B, 0x2C, 0x1D, 0x1E, 0x1C, 0x20, 0x0C],
      plan: 'centre:10,up:150,centre:20,down:100',
      init: { screen: 4, path: 0x04, e8e: 0x80, e6b: 0, x0: 0x78 } },
    { name: 'thief', golden: 'thief_idle.txt', check: [0x90, 0x1B, 0x1F, 0x11, 0x28, 0x63], plan: 'centre:3400' },
];
/* never compared: $2B scratch pointer, $58 thief direction byte, $14 state flag */
const SKIP = new Set([0x2B, 0x58, 0x14]);

function parsePlan(plan) {
    const out = [];
    for (const item of plan.split(',')) {
        const [spec, n] = item.split(':');
        const [d, fire] = spec.split('+');
        let b = { up: 1, down: 2, left: 4, right: 8 }[d] || 0;
        if (d === 'fire' || fire) b |= 0x10;            /* tools/atari_trace.py: anything after '+' = fire */
        out.push([b, Number(n), spec]);
    }
    return out;
}

function readGolden(file) {
    const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/).filter(l => l.trim());
    const cols = lines[0].trim().split(/\s+/).slice(2).map(h => parseInt(h, 16));
    const rows = lines.slice(1).map(l => l.trim().split(/\s+/).slice(2).map(h => parseInt(h, 16)));
    return { cols, rows };
}

const hex = v => v.toString(16).toUpperCase().padStart(2, '0');
const sym = symbolsFromNoi(noi);
const S = n => requireSymbol(sym, n);

async function waitState(v, ms = 20000) {
    const t0 = Date.now();
    for (;;) {
        const s = (await readBytes(S('_dbg_state'), 1))[0];
        if (s === v) return;
        if (Date.now() - t0 > ms) throw new Error(`dbg_state stuck at ${s}, wanted ${v}`);
        await sleep(30);
    }
}

async function poke(name, v, off = 0) { await writeBytes(S(name) + off, [v & 0xFF]); }

async function runScenario(sc) {
    const g = readGolden(path.join(ROOT, 'tests', 'golden', sc.golden));
    const plan = parsePlan(sc.plan);
    const total = plan.reduce((a, p) => a + p[1], 0);
    if (total !== g.rows.length) throw new Error(`${sc.name}: plan ${total} frames, golden ${g.rows.length}`);
    if (plan.length > PLAN_MAX) throw new Error(`${sc.name}: plan too long`);
    const col = a => g.cols.indexOf(a);

    await waitState(1);
    /* checkpoint state, then the scenario's --init pokes */
    const r0 = g.rows[0];
    await poke('_frame_90', r0[col(0x90)] - 1);
    await poke('_frame_8f', col(0x8F) >= 0 ? r0[col(0x8F)] - 1 : r0[col(0x90)] + 0x12 - 1);
    await poke('_game_time', 0x49);
    await poke('_thief_x', 0xB1);
    await poke('_thief_path', 0x0B);
    await poke('_thief_anim', 3);
    const ini = sc.init || {};
    for (const [k, v] of Object.entries(ini)) {
        if (k[0] === 'x') await poke('_kop_xs', v, Number(k.slice(1)));
        else await poke({ screen: '_kop_screen', path: '_kop_path', c1c: '_kop_c1c', e8e: '_elev_8e', e6b: '_elev_6b' }[k], v);
    }
    const pb = new Array(PLAN_MAX * 3).fill(0);
    plan.forEach(([b, n], i) => { pb[i * 3] = b; pb[i * 3 + 1] = n & 0xFF; pb[i * 3 + 2] = n >> 8; });
    await writeBytes(S('_dbg_plan'), pb);
    await poke('_dbg_go', 1);

    /* drain the ring */
    const rows = [];
    let tail = 0, idle = 0;
    while (rows.length < total) {
        const head = (await readBytes(S('_trace_head'), 1))[0];
        const n = (head - tail) & 0xFF;
        if (!n) {
            if (++idle > 400) throw new Error(`${sc.name}: no trace progress at row ${rows.length}`);
            await sleep(20);
            continue;
        }
        idle = 0;
        const ring = await readBytes(S('_trace_ring'), TRACE_ROWS * TRACE_COLS);
        for (let i = 0; i < n; i++) {
            const slot = (tail + i) % TRACE_ROWS;
            rows.push(ring.slice(slot * TRACE_COLS, (slot + 1) * TRACE_COLS));
        }
        tail = (tail + n) & 0xFF;
        await poke('_trace_tail', tail);
    }
    await waitState(3);
    await poke('_dbg_go', 0);

    /* write the C trace in golden format (golden's columns) */
    const outDir = path.join(ROOT, 'build', 'c_trace');
    fs.mkdirSync(outDir, { recursive: true });
    const specs = plan.flatMap(([, n, spec]) => new Array(n).fill(spec));
    const recCol = a => REC.indexOf(a);
    const lines = ['frame input  ' + g.cols.map(a => a.toString(16).toUpperCase().padStart(3, '0')).join(' ')];
    rows.forEach((r, f) => lines.push(`${String(f).padStart(4)} ${specs[f].padEnd(8)} ` +
        g.cols.map(a => (recCol(a) >= 0 ? hex(r[recCol(a)]) : '--') + ' ').join(' ')));
    fs.writeFileSync(path.join(outDir, `${sc.name}.txt`), lines.join('\n') + '\n');

    /* compare */
    let bad = 0, shown = 0;
    const info = {};
    for (let f = 0; f < total; f++) {
        const r = rows[f], e = g.rows[f];
        const diffs = [];
        for (const a of g.cols) {
            if (SKIP.has(a) || recCol(a) < 0) continue;
            const m = (sc.mask && sc.mask[a]) ?? 0xFF;
            const got = r[recCol(a)] & m, exp = e[col(a)] & m;
            if (got === exp) continue;
            if (sc.check.includes(a)) diffs.push(`$${hex(a)}:${hex(got)}!=${hex(exp)}`);
            else info[a] = (info[a] || 0) + 1;
        }
        if (diffs.length) {
            bad++;
            if (shown++ < 8) {
                console.log(`  frame ${f} (${specs[f]}): ${diffs.join(' ')}`);
                if (shown === 1) console.log('    C state: ' + REC.map((a, i) => `$${hex(a)}=${hex(r[i])}`).join(' '));
            }
        }
    }
    const infoTxt = Object.entries(info).map(([a, n]) => `$${hex(Number(a))}:${n}`).join(' ');
    console.log(`${sc.name.padEnd(8)} mismatching frames: ${bad} of ${total}` + (infoTxt ? `   (info, not checked: ${infoTxt})` : ''));
    return bad;
}

async function main() {
    await init();
    await callTool('mesen_load_rom', { filepath: rom });
    await sleep(1000);
    let fail = 0;
    for (const sc of SCENARIOS) {
        if (only.length && !only.includes(sc.name)) continue;
        if (await runScenario(sc)) fail++;
    }
    console.log(fail ? `FAILED: ${fail}` : 'all goldens match');
    return fail;
}

main().then(f => process.exit(f ? 1 : 0), e => { console.error(e); process.exit(2); });
