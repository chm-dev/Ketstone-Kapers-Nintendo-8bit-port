<#
.SYNOPSIS
  Build the Keystone Kapers Game Boy ROM (one ROM for Game Boy Color and original Game Boy) with GBDK-2020
  (sm83) -> roms/keystone_kapers.gbc.

.DESCRIPTION
  Header $0143 = $80 (CGB compatible): main_gbc.c reads _cpu at boot and runs the CGB colour path on a
  Game Boy Color, the DMG 4-shade path on a Game Boy (gb_color flag; no separate DMG build).
  Shared logic: src/engine.c, src/obstacle.c (pure C, src/platform.h), src/spr_data.c (sprite tiles and
  metasprites), src/sound_data.c (sound tables).  GB side: src/gbc/*.c - main_gbc.c (loop, renderer,
  HUD), dyn_gbc.c (escalators/elevator), sound_gbc.c (GB APU), gbc_data.c (bank 0 tables) and
  gbc_bank<N>.c (generated by tools/gen_gbc_assets.py), plus the DMG shades src/dmg/dmg_data.c and
  dmg_bank<N>.c (tools/gen_dmg_assets.py, banks from GBC_ROM_BANKS up); bank files compiled with -Wf-bo<N>.
  The NES-only files (src/main.c, dyn.c, sound.c, bg_data*, dyn_data*, hud_data*, trace.c) are not used.
  Link: MBC5 (-yt0x19), $Banks x 16 KB, in build/gbc; roms/<Name>.gbc + roms/<Name>_gb.map/.noi
  (roms/<Name>.map/.noi belong to the NES build).
  After the link the script fails unless the header, size, checksum, every .map area's bank window and the
  .noi symbols are right (the linker does not reliably fail on bank overflow).
  build_dmg.ps1 = this script + a copy to roms/<Name>.gb.

.EXAMPLE
  .\build_gbc.ps1
#>
[CmdletBinding()]
param(
    [int]$Banks = 8,
    [string]$Name = 'keystone_kapers'
)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot
$lcc = Join-Path $PSScriptRoot 'gbdk\bin\lcc.exe'
if (-not (Test-Path $lcc)) { throw "GBDK lcc not found at $lcc" }
$objDir = Join-Path $PSScriptRoot 'build\gbc'
$outDir = Join-Path $PSScriptRoot 'roms'
New-Item -ItemType Directory -Force $objDir, $outDir | Out-Null
$linkOut = Join-Path $objDir "$($Name)_gb.gb"   # lcc picks the output type from the extension; .map/.noi land beside it
$rom = Join-Path $outDir "$Name.gbc"

function Fingerprint([string[]]$files) {
    $ms = New-Object System.IO.MemoryStream
    foreach ($f in $files) {
        $b = [System.Text.Encoding]::UTF8.GetBytes(([System.IO.File]::ReadAllText((Join-Path $PSScriptRoot $f)) -replace "`r`n", "`n"))
        $ms.Write($b, 0, $b.Length)
    }
    $sha = [System.Security.Cryptography.SHA1]::Create().ComputeHash($ms.ToArray())
    return -join ($sha[0..7] | ForEach-Object { $_.ToString('x2') })
}
# ---- generated data: present, fresh, banks not overlapping ----
$hdr = Get-Content 'src\gbc\gbc_data.h' -Raw
if ($hdr -notmatch 'GBC_ROM_BANKS (\d+)u') { throw 'src/gbc/gbc_data.h: run python -I tools/gen_gbc_assets.py --emit' }
$gbcBanks = [int]$Matches[1]
# gbc_data.c copies palettes / step indices out of src/spr_data.c and src/sound_data.c: stale when they change
$fp = Fingerprint @('src\spr_data.c', 'src\sound_data.c')
if ($hdr -notmatch "GBC_SRC_FINGERPRINT `"$fp`"") {
    throw "src/gbc/gbc_data.* does not match src/spr_data.c + src/sound_data.c (fingerprint $fp): run python -I tools/gen_gbc_assets.py --emit"
}
$dhdr = Get-Content 'src\dmg\dmg_data.h' -Raw
if ($dhdr -notmatch 'DMG_FIRST_BANK (\d+)u') { throw 'src/dmg/dmg_data.h: run python -I tools/gen_dmg_assets.py --emit' }
$dmgFirst = [int]$Matches[1]
if ($dhdr -notmatch 'DMG_ROM_BANKS (\d+)u') { throw 'src/dmg/dmg_data.h: no DMG_ROM_BANKS' }
$dmgBanks = [int]$Matches[1]
# dmg_data.* bakes the sprite tiles of src/spr_data.c
$fpd = Fingerprint @('src\spr_data.c')
if ($dhdr -notmatch "DMG_SRC_FINGERPRINT `"$fpd`"") { throw "src/dmg/dmg_data.* does not match src/spr_data.c (fingerprint $fpd): run python -I tools/gen_dmg_assets.py --emit" }
if ($dmgFirst -lt $gbcBanks) { throw "DMG data starts at bank $dmgFirst but the GBC data uses banks 1..$($gbcBanks - 1): run python -I tools/gen_dmg_assets.py --emit (after gen_gbc_assets.py)" }
if ($dmgBanks -gt $Banks) { throw "GB data needs $dmgBanks banks, -Banks is $Banks" }
foreach ($f in Get-ChildItem 'src/gbc' -Filter 'gbc_bank*.c') { if ($f.Name -match '(\d+)' -and [int]$Matches[1] -ge $gbcBanks) { throw "stale $($f.Name) (GBC_ROM_BANKS $gbcBanks): re-run gen_gbc_assets.py --emit" } }
foreach ($f in Get-ChildItem 'src/dmg' -Filter 'dmg_bank*.c') { if ($f.Name -match '(\d+)' -and ([int]$Matches[1] -lt $dmgFirst -or [int]$Matches[1] -ge $dmgBanks)) { throw "stale $($f.Name) (DMG banks $dmgFirst..$($dmgBanks - 1)): re-run gen_dmg_assets.py --emit" } }

$sources = @('src/engine.c', 'src/obstacle.c', 'src/spr_data.c', 'src/sound_data.c',
             'src/gbc/main_gbc.c', 'src/gbc/dyn_gbc.c', 'src/gbc/sound_gbc.c', 'src/gbc/gbc_data.c', 'src/dmg/dmg_data.c')
$sources += Get-ChildItem 'src/gbc' -Filter 'gbc_bank*.c' | Sort-Object Name | ForEach-Object { "src/gbc/$($_.Name)" }
$sources += Get-ChildItem 'src/dmg' -Filter 'dmg_bank*.c' | Sort-Object Name | ForEach-Object { "src/dmg/$($_.Name)" }

$failures = New-Object System.Collections.Generic.List[string]
function Fail([string]$msg) { $failures.Add($msg); Write-Host "  FAIL  $msg" -ForegroundColor Red }
function Pass([string]$msg) { Write-Host "  ok    $msg" }

# ---- compile ----
$objs = @()
foreach ($src in $sources) {
    $base = [IO.Path]::GetFileNameWithoutExtension($src)
    $obj = Join-Path $objDir "$base.o"
    $a = @('-msm83:gb', '-Isrc', '-Isrc/gbc', '-Isrc/dmg')
    if ($base -match '^(gbc|dmg)_bank(\d+)$') { $a += "-Wf-bo$($Matches[2])" }
    $a += @('-c', '-o', $obj, $src)
    Write-Host "CC  $src"
    & $lcc @a
    if ($LASTEXITCODE -ne 0) { throw "compile failed: $src" }
    $objs += $obj
}

# ---- link ----
Write-Host "LD  $rom"
# -Wm-yc: header $0143 = $80 (CGB compatible; -yC would be $C0 = CGB only)
$l = @('-msm83:gb', '-Wl-j', '-Wl-m', '-Wl-yt0x19', "-Wl-yo$Banks", '-Wm-yc', '-Wm-ynKEYSTONE', '-o', $linkOut) + $objs
& $lcc @l
if ($LASTEXITCODE -ne 0) { throw 'link failed' }
Copy-Item -Force $linkOut $rom
$map = Join-Path $outDir "$($Name)_gb.map"
$noi = Join-Path $outDir "$($Name)_gb.noi"
Copy-Item -Force (Join-Path $objDir "$($Name)_gb.map") $map
Copy-Item -Force (Join-Path $objDir "$($Name)_gb.noi") $noi

# ---- checks ----
Write-Host "Checks for $rom"
$bytes = [IO.File]::ReadAllBytes($rom)
if ($bytes.Length -eq $Banks * 16384) { Pass "size $($bytes.Length) bytes = $Banks banks" }
else { Fail "size $($bytes.Length) bytes, expected $($Banks * 16384)" }
if ($bytes[0x143] -eq 0x80) { Pass 'header $0143 = $80 (CGB compatible: colour on GBC, shades on DMG)' }
else { Fail ('header $0143 = ${0:X2}, expected $80' -f $bytes[0x143]) }
if ($bytes[0x147] -eq 0x19) { Pass 'header $0147 = $19 (MBC5)' }
else { Fail ('header $0147 = ${0:X2}, expected $19 (MBC5)' -f $bytes[0x147]) }
$sizeCode = [int][Math]::Log($Banks / 2, 2)
if ($bytes[0x148] -eq $sizeCode) { Pass ('header $0148 = ${0:X2} ({1} banks)' -f $bytes[0x148], $Banks) }
else { Fail ('header $0148 = ${0:X2}, expected ${1:X2}' -f $bytes[0x148], $sizeCode) }
$sum = 0
for ($i = 0x134; $i -le 0x14C; $i++) { $sum = ($sum - $bytes[$i] - 1) -band 0xFF }
if ($sum -eq $bytes[0x14D]) { Pass ('header checksum $014D = ${0:X2}' -f $sum) }
else { Fail ('header checksum $014D = ${0:X2}, computed ${1:X2}' -f $bytes[0x14D], $sum) }
Pass "data banks: GBC 1..$($gbcBanks - 1), DMG $dmgFirst..$($dmgBanks - 1)"

# .map: "<area> <addr 8 hex> <size 8 hex> = ..."; addr = bank << 16 | offset
if (-not (Test-Path $map)) { Fail "missing $map" }
else {
    $rx = '^(_\w+)\s+([0-9A-Fa-f]{8})\s+([0-9A-Fa-f]{8})\s+='
    $bad = 0
    $bankEnd = @{}
    foreach ($line in Get-Content $map) {
        if ($line -notmatch $rx) { continue }
        $area = $Matches[1]
        if ($area -like '_HEADER*' -or $area -like '_CABS*' -or $area -like '_DABS*') { continue }
        $addr = [Convert]::ToInt32($Matches[2], 16)
        $size = [Convert]::ToInt32($Matches[3], 16)
        if ($size -eq 0) { continue }
        $bank = $addr -shr 16
        $off = $addr -band 0xFFFF
        $end = $off + $size
        if ($area -eq '_HRAM') { $ok = ($off -ge 0xFF80) -and ($end -le 0xFFFF); $win = 'HRAM' }
        elseif ($area -match '^_(DATA|BSS|INITIALIZED|HEAP)') { $ok = ($off -ge 0xC000) -and ($end -le 0xE000); $win = 'WRAM' }
        elseif ($bank -eq 0) { $ok = $end -le 0x4000; $win = 'bank 0 $0000-$3FFF' }
        else { $ok = ($bank -lt $Banks) -and ($off -ge 0x4000) -and ($end -le 0x8000); $win = "bank $bank `$4000-`$7FFF" }
        if ($area -notmatch '^_(DATA|BSS|INITIALIZED|HEAP|HRAM)') {
            if (-not $bankEnd.ContainsKey($bank) -or $bankEnd[$bank] -lt $end) { $bankEnd[$bank] = $end }
        }
        if (-not $ok) { $bad++; Fail ('{0} bank {1} ${2:X4}-${3:X4} outside {4}' -f $area, $bank, $off, ($end - 1), $win) }
    }
    if ($bad -eq 0) { Pass 'every map area is inside its window' }
    foreach ($b in 1..($dmgBanks - 1)) { if (-not $bankEnd.ContainsKey($b)) { Fail "bank $b has no data in the .map" } }
    foreach ($b in ($bankEnd.Keys | Sort-Object)) {
        $limit = if ($b -eq 0) { 0x4000 } else { 0x8000 }
        Write-Host ('          bank {0} ends at ${1:X4} ({2} bytes free)' -f $b, $bankEnd[$b], ($limit - $bankEnd[$b]))
    }
}
if (-not (Test-Path $noi)) { Fail "missing $noi" }
else {
    $noiText = Get-Content $noi -Raw
    foreach ($sym in @('_kop_screen', '_play_on', '_game_time', '_gb_color')) {
        if ($noiText -match "DEF $([regex]::Escape($sym))\s") { Pass "symbol $sym in .noi" } else { Fail "symbol $sym missing from .noi" }
    }
}
if ($failures.Count -gt 0) { Write-Host "$($failures.Count) check(s) failed" -ForegroundColor Red; exit 1 }
Write-Host "OK   $rom" -ForegroundColor Green
