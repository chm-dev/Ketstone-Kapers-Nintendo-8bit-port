#!/usr/bin/env python3
"""Pipeline-proof asset: turn the live Atari mode-C bitmap rows into deduplicated NES tiles.

Reads a RAM dump (default assets/atari/runtime/play1), decodes the display list with
render_dl.decode(), packs the 160-px 1-bpp scanlines into 8x8 tiles (colour index 1 only),
dedupes them and writes src/proof_data.c/.h (tile CHR, 20x24 nametable).  Prints the
unique tile count, an early number for the NES CHR budget.

Usage: python tools/gen_proof.py [RAM.bin]
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from render_dl import decode

ROOT = Path(__file__).resolve().parent.parent
ram = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / 'assets/atari/runtime/play1/ram_0000_ffff.bin').read_bytes()
rows, _ = decode(ram, 0x0A00)
scan = []
for r in rows:
    if r[0] == 'blank':
        scan += [[0] * 160] * r[1]
    elif r[1] == 0xC:
        bits = []
        for k in range(20):
            v = ram[r[2] + k]
            bits += [(v >> s) & 1 for s in range(7, -1, -1)]
        scan.append(bits)
    else:
        scan += [[0] * 160] * 8
TR = 24
scan = scan[:TR * 8] + [[0] * 160] * max(0, TR * 8 - len(scan))
tiles, index, nt = [bytes(16)], {bytes(16): 0}, []
for ty in range(TR):
    for tx in range(20):
        p0 = bytes(sum(scan[ty * 8 + y][tx * 8 + x] << (7 - x) for x in range(8)) for y in range(8))
        t = p0 + bytes(8)
        if t not in index:
            index[t] = len(tiles); tiles.append(t)
        nt.append(index[t])
assert len(tiles) <= 256, len(tiles)
print(f'{len(tiles)} unique tiles for {TR}x20')
h = ROOT / 'src/proof_data.h'
h.write_text('#ifndef PROOF_DATA_H\n#define PROOF_DATA_H\n#include <stdint.h>\n'
             f'#define PROOF_TILES {len(tiles)}u\n#define PROOF_W 20u\n#define PROOF_H {TR}u\n'
             'extern const uint8_t proof_chr[];\nextern const uint8_t proof_map[];\n#endif\n')
c = ['#include "proof_data.h"', '/* generated by tools/gen_proof.py - do not edit */', 'const uint8_t proof_chr[] = {']
for t in tiles:
    c.append('  ' + ','.join(f'0x{b:02X}' for b in t) + ',')
c += ['};', 'const uint8_t proof_map[] = {']
for i in range(0, len(nt), 20):
    c.append('  ' + ','.join(str(v) for v in nt[i:i + 20]) + ',')
c.append('};')
(ROOT / 'src/proof_data.c').write_text('\n'.join(c) + '\n')
