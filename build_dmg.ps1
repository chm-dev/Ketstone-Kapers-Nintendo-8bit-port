<#
.SYNOPSIS
  Build the Keystone Kapers original Game Boy (DMG, 4 grey shades) ROM with GBDK-2020 (sm83) -> roms/keystone_kapers.gb.

.DESCRIPTION
  Same sources as build_gbc.ps1 (engine.c, obstacle.c, spr_data.c, sound_data.c, src/gbc/main_gbc.c, dyn_gbc.c,
  sound_gbc.c, gbc_data.c = sound tables only) compiled with -DGB_DMG (no CGB code paths), plus the DMG data
  src/dmg/dmg_data.c and dmg_bank<N>.c (generated by tools/gen_dmg_assets.py, compiled with -Wf-bo<N>).
  The CGB screen/HUD/palette data in src/gbc/gbc_bank*.c is not used.
  Link: MBC5 (-yt0x19), plain DMG header ($0143 = 0), $Banks x 16 KB.
  After the link the script fails unless the header, size, checksum, every .map area's bank window and the
  .noi symbols are right (the linker does not reliably fail on bank overflow).

.EXAMPLE
  .\build_dmg.ps1
#>
[CmdletBinding()]
param(
    [int]$Banks = 4,
    [string]$Name = 'keystone_kapers'
)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot
$lcc = Join-Path $PSScriptRoot 'gbdk\bin\lcc.exe'
if (-not (Test-Path $lcc)) { throw "GBDK lcc not found at $lcc" }
$objDir = Join-Path $PSScriptRoot 'build\dmg'
$outDir = Join-Path $PSScriptRoot 'roms'
New-Item -ItemType Directory -Force $objDir, $outDir | Out-Null
$rom = Join-Path $outDir "$Name.gb"
$linkOut = Join-Path $objDir "$($Name)_dmg.gb"      # .map/.noi land beside it: roms/<Name>.map/.noi belong to the NES/GBC builds

function Fingerprint([string[]]$files) {
    $ms = New-Object System.IO.MemoryStream
    foreach ($f in $files) {
        $b = [System.Text.Encoding]::UTF8.GetBytes(([System.IO.File]::ReadAllText((Join-Path $PSScriptRoot $f)) -replace "`r`n", "`n"))
        $ms.Write($b, 0, $b.Length)
    }
    $sha = [System.Security.Cryptography.SHA1]::Create().ComputeHash($ms.ToArray())
    return -join ($sha[0..7] | ForEach-Object { $_.ToString('x2') })
}
$hdr = Get-Content 'src\dmg\dmg_data.h' -Raw
if ($hdr -notmatch 'DMG_ROM_BANKS (\d+)u') { throw 'src/dmg/dmg_data.h: run python -I tools/gen_dmg_assets.py --emit' }
if ([int]$Matches[1] -gt $Banks) { throw "dmg data needs $($Matches[1]) banks, -Banks is $Banks" }
# dmg_data.* bakes the sprite tiles of src/spr_data.c; gbc_data.c (sound tables) copies step indices out of spr_data.c + sound_data.c
$fp = Fingerprint @('src\spr_data.c')
if ($hdr -notmatch "DMG_SRC_FINGERPRINT `"$fp`"") { throw "src/dmg/dmg_data.* does not match src/spr_data.c (fingerprint $fp): run python -I tools/gen_dmg_assets.py --emit" }
$ghdr = Get-Content 'src\gbc\gbc_data.h' -Raw
$fp2 = Fingerprint @('src\spr_data.c', 'src\sound_data.c')
if ($ghdr -notmatch "GBC_SRC_FINGERPRINT `"$fp2`"") { throw "src/gbc/gbc_data.* does not match spr_data.c + sound_data.c (fingerprint $fp2): run python -I tools/gen_gbc_assets.py --emit" }

$sources = @('src/engine.c', 'src/obstacle.c', 'src/spr_data.c', 'src/sound_data.c',
             'src/gbc/main_gbc.c', 'src/gbc/dyn_gbc.c', 'src/gbc/sound_gbc.c', 'src/gbc/gbc_data.c', 'src/dmg/dmg_data.c')
$sources += Get-ChildItem 'src/dmg' -Filter 'dmg_bank*.c' | Sort-Object Name | ForEach-Object { "src/dmg/$($_.Name)" }

$failures = New-Object System.Collections.Generic.List[string]
function Fail([string]$msg) { $failures.Add($msg); Write-Host "  FAIL  $msg" -ForegroundColor Red }
function Pass([string]$msg) { Write-Host "  ok    $msg" }

# ---- compile ----
$objs = @()
foreach ($src in $sources) {
    $base = [IO.Path]::GetFileNameWithoutExtension($src)
    $obj = Join-Path $objDir "$base.o"
    $a = @('-msm83:gb', '-DGB_DMG', '-Isrc', '-Isrc/gbc', '-Isrc/dmg')
    if ($base -match '^dmg_bank(\d+)$') { $a += "-Wf-bo$($Matches[1])" }
    $a += @('-c', '-o', $obj, $src)
    Write-Host "CC  $src"
    & $lcc @a
    if ($LASTEXITCODE -ne 0) { throw "compile failed: $src" }
    $objs += $obj
}

# ---- link ----
Write-Host "LD  $rom"
$l = @('-msm83:gb', '-Wl-j', '-Wl-m', '-Wl-yt0x19', "-Wl-yo$Banks", '-Wm-ynKEYSTONE', '-o', $linkOut) + $objs
& $lcc @l
if ($LASTEXITCODE -ne 0) { throw 'link failed' }
Copy-Item -Force $linkOut $rom
Copy-Item -Force (Join-Path $objDir "$($Name)_dmg.map") (Join-Path $outDir "$($Name)_dmg.map")
Copy-Item -Force (Join-Path $objDir "$($Name)_dmg.noi") (Join-Path $outDir "$($Name)_dmg.noi")

# ---- checks ----
Write-Host "Checks for $rom"
$bytes = [IO.File]::ReadAllBytes($rom)
if ($bytes.Length -eq $Banks * 16384) { Pass "size $($bytes.Length) bytes = $Banks banks" }
else { Fail "size $($bytes.Length) bytes, expected $($Banks * 16384)" }
if ($bytes[0x143] -eq 0x00) { Pass 'header $0143 = $00 (DMG)' }
else { Fail ('header $0143 = ${0:X2}, expected $00' -f $bytes[0x143]) }
if ($bytes[0x147] -eq 0x19) { Pass 'header $0147 = $19 (MBC5)' }
else { Fail ('header $0147 = ${0:X2}, expected $19 (MBC5)' -f $bytes[0x147]) }
$sizeCode = [int][Math]::Log($Banks / 2, 2)
if ($bytes[0x148] -eq $sizeCode) { Pass ('header $0148 = ${0:X2} ({1} banks)' -f $bytes[0x148], $Banks) }
else { Fail ('header $0148 = ${0:X2}, expected ${1:X2}' -f $bytes[0x148], $sizeCode) }
$sum = 0
for ($i = 0x134; $i -le 0x14C; $i++) { $sum = ($sum - $bytes[$i] - 1) -band 0xFF }
if ($sum -eq $bytes[0x14D]) { Pass ('header checksum $014D = ${0:X2}' -f $sum) }
else { Fail ('header checksum $014D = ${0:X2}, computed ${1:X2}' -f $bytes[0x14D], $sum) }

# .map: "<area> <addr 8 hex> <size 8 hex> = ..."; addr = bank << 16 | offset
$map = Join-Path $outDir "$($Name)_dmg.map"
if (-not (Test-Path $map)) { Fail "missing $map" }
else {
    $rx = '^(_\w+)\s+([0-9A-Fa-f]{8})\s+([0-9A-Fa-f]{8})\s+='
    $bad = 0
    $bankEnd = @{}
    foreach ($line in Get-Content $map) {
        if ($line -notmatch $rx) { continue }
        $area = $Matches[1]
        if ($area -like '_HEADER*' -or $area -like '_CABS*' -or $area -like '_DABS*') { continue }
        $addr = [Convert]::ToInt32($Matches[2], 16)
        $size = [Convert]::ToInt32($Matches[3], 16)
        if ($size -eq 0) { continue }
        $bank = $addr -shr 16
        $off = $addr -band 0xFFFF
        $end = $off + $size
        if ($area -eq '_HRAM') { $ok = ($off -ge 0xFF80) -and ($end -le 0xFFFF); $win = 'HRAM' }
        elseif ($area -match '^_(DATA|BSS|INITIALIZED|HEAP)') { $ok = ($off -ge 0xC000) -and ($end -le 0xE000); $win = 'WRAM' }
        elseif ($bank -eq 0) { $ok = $end -le 0x4000; $win = 'bank 0 $0000-$3FFF' }
        else { $ok = ($bank -lt $Banks) -and ($off -ge 0x4000) -and ($end -le 0x8000); $win = "bank $bank `$4000-`$7FFF" }
        if ($area -notmatch '^_(DATA|BSS|INITIALIZED|HEAP|HRAM)') {
            if (-not $bankEnd.ContainsKey($bank) -or $bankEnd[$bank] -lt $end) { $bankEnd[$bank] = $end }
        }
        if (-not $ok) { $bad++; Fail ('{0} bank {1} ${2:X4}-${3:X4} outside {4}' -f $area, $bank, $off, ($end - 1), $win) }
    }
    if ($bad -eq 0) { Pass 'every map area is inside its window' }
    foreach ($b in ($bankEnd.Keys | Sort-Object)) {
        $limit = if ($b -eq 0) { 0x4000 } else { 0x8000 }
        Write-Host ('          bank {0} ends at ${1:X4} ({2} bytes free)' -f $b, $bankEnd[$b], ($limit - $bankEnd[$b]))
    }
}
$noi = Join-Path $outDir "$($Name)_dmg.noi"
if (-not (Test-Path $noi)) { Fail "missing $noi" }
else {
    $noiText = Get-Content $noi -Raw
    foreach ($sym in @('_kop_screen', '_play_on', '_game_time')) {
        if ($noiText -match "DEF $([regex]::Escape($sym))\s") { Pass "symbol $sym in .noi" } else { Fail "symbol $sym missing from .noi" }
    }
}
if ($failures.Count -gt 0) { Write-Host "$($failures.Count) check(s) failed" -ForegroundColor Red; exit 1 }
Write-Host "OK   $rom" -ForegroundColor Green
